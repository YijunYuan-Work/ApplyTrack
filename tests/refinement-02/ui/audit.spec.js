import { expect, test } from '@playwright/test'
import { application, backend, lead, nav, noOverflow, signIn, spreadsheet } from './fixtures.js'

test('CRUD, details, sorting, filtering, pagination and persisted refresh', async ({ page, context }) => {
  test.setTimeout(60000)
  const state = await backend(context, Array.from({ length: 25 }, (_, i) => application(i + 1, i === 0 ? { status: 'Rejected', last_updated: '2027-01-01' } : {})))
  await signIn(page)
  await nav(page, 'List')
  await expect(page.locator('.application-card')).toHaveCount(10)
  await expect(page.locator('.application-card').first()).toContainText('Synthetic 25')
  await page.getByRole('combobox', { name: 'Sort', exact: true }).selectOption('lastUpdated')
  await expect(page.locator('.application-card').first()).toContainText('Synthetic 1')
  await page.getByRole('button', { name: 'Filter status: Rejected', exact: true }).click()
  await expect(page.locator('.application-card')).toHaveCount(1)
  await expect(page.locator('.application-card')).toContainText('Synthetic 1')
  await nav(page, 'Clear filters')
  await page.getByRole('button', { name: 'Next', exact: true }).first().click()
  await expect(page.getByText('Page 2 of 3').first()).toBeVisible()
  await page.getByLabel('Search', { exact: true }).fill('Synthetic 25')
  await expect(page.locator('.application-card')).toHaveCount(1)
  await nav(page, 'Clear filters')
  await nav(page, 'Add application')
  await page.getByLabel('Company', { exact: false }).fill('Created fixture')
  await page.getByLabel('Role', { exact: false }).fill('Auditor')
  await page.getByLabel('Notes', { exact: true }).fill('Persisted audit note')
  await page.locator('button[type="submit"]').click()
  await expect(page.getByText('Created fixture', { exact: true })).toBeVisible()
  await nav(page, 'List')
  await page.getByLabel('Search', { exact: true }).fill('Created fixture')
  await nav(page, 'Edit')
  await page.getByLabel('Role', { exact: false }).fill('Updated auditor')
  await page.locator('button[type="submit"]').click()
  await expect(page.getByText('Updated auditor', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByText('Created fixture', { exact: true })).toBeVisible()
  expect(state.applications.find((row) => row.company === 'Created fixture').role).toBe('Updated auditor')
  await nav(page, 'List')
  await page.getByLabel('Search', { exact: true }).fill('Created fixture')
  page.once('dialog', (dialog) => dialog.accept())
  await nav(page, 'Delete')
  await expect(page.getByText('Created fixture', { exact: true })).toHaveCount(0)
  expect(state.blocked).toEqual([])
})

test('RF-03 F02/F03: role-only edits preserve notes and nullable rows load alongside valid rows', async ({ page, context }) => {
  const notes = '  Cover letter: Yes\r\nReferral: No\r\nLast updated: interview pending\r\n\r\nKeep this note  \r\n'
  const state = await backend(context, [application(1, { notes })])
  await signIn(page)
  await nav(page, 'Edit')
  await expect(page.getByRole('textbox', { name: 'Notes', exact: true })).toHaveValue(notes.replaceAll('\r\n', '\n'))
  await page.getByLabel('Role', { exact: false }).fill('Updated')
  await page.locator('button[type="submit"]').click()
  await expect(page).toHaveURL(/dashboard$/)
  await expect.poll(() => state.applications[0].notes).toBe(notes)
  state.applications.push(application(2, { notes: null }))
  await page.reload()
  await expect(page.locator('.board-card')).toHaveCount(2)
  await expect(page.locator('.form-error')).toHaveCount(0)
  await page.locator('.board-card').filter({ hasText: 'Synthetic 2' }).getByRole('button', { name: 'Edit', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Notes', exact: true })).toHaveValue('')
  await nav(page, 'Back to dashboard')
  await page.locator('.board-card').filter({ hasText: 'Synthetic 1' }).getByRole('button', { name: 'Edit', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Notes', exact: true })).toHaveValue(notes.replaceAll('\r\n', '\n'))
  expect(state.blocked).toEqual([])
})

