test('full edit version conflict retries without losing concurrent status, rounds or unrelated data', async ({ page, context }) => {
  const state = await setup(page, context, [application(1)])
  await nav(page, 'Edit')
  await page.getByRole('textbox', { name: 'Notes', exact: true }).fill('Edited note')
  await submit(page).click()
  const save = await operation(state)
  Object.assign(state.applications[0], { status: 'Interview', interview_count: 4, salary: '125000', contact: 'New recruiter', updated_at: '2026-01-05T00:00:00.000Z' })
  await save.respond()
  const retry = await operation(state, 1)
  expect(retry.body).toEqual({ notes: 'Edited note', last_updated: expect.any(String) })
  expect(new URLSearchParams(retry.query).get('user_id')).toBe(`eq.${state.user.id}`)
  await retry.respond()
  await expect(page).toHaveURL(/dashboard$/)
  await expect(status(page)).toHaveValue('Interview')
  await nav(page, 'List')
  await openDetails(page)
  await expect(page.locator('.detail-salary dd')).toHaveText('125000')
  await expect(page.locator('.detail-interviews dd')).toHaveText('4')
  await closeDetails(page)
  expect(state.applications[0]).toMatchObject({ notes: 'Edited note', salary: '125000', contact: 'New recruiter', interview_count: 4, status: 'Interview' })
})

test('bounded full edit conflicts surface failure; correction and retry preserve data', async ({ page, context }) => {
  const state = await setup(page, context, [application(1)])
  await nav(page, 'Edit')
  await page.getByRole('textbox', { name: 'Notes', exact: true }).fill('Retry this note')
  await submit(page).click()
  for (let i = 0; i < 3; i += 1) {
    const save = await operation(state, i)
    state.applications[0].updated_at = `2026-02-0${i + 1}T00:00:00.000Z`
    await save.respond()
  }
  await expect(page.getByRole('alert')).toContainText('changed while saving')
  await expect(page.getByRole('textbox', { name: 'Notes', exact: true })).toHaveValue('Retry this note')
  expect(state.applications[0].notes).toBe('')
  await submit(page).click()
  await (await operation(state, 3)).respond()
  await expect(page).toHaveURL(/dashboard$/)
})

