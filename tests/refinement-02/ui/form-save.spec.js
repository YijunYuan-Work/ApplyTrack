for (const edit of [false, true]) {
  test(`server failure preserves input and retry succeeds (${edit ? 'edit' : 'create'})`, async ({ page, context }) => {
    const state = await setup(page, context, edit ? [application(1)] : [])
    if (edit) await nav(page, 'Edit')
    else await newForm(page)
    await page.getByRole('textbox', { name: 'Notes', exact: true }).fill('Keep these unsaved notes')
    await submit(page).click()
    await (await operation(state)).fail()
    await expect(page.getByRole('alert')).toHaveText('Synthetic save failure')
    await expect(page.getByRole('textbox', { name: 'Notes', exact: true })).toHaveValue('Keep these unsaved notes')
    await expect(submit(page)).toBeEnabled()
    await expect(page).toHaveURL(edit ? /edit$/ : /new$/)
    await submit(page).click()
    await (await operation(state, 1)).respond()
    await expect(page).toHaveURL(/dashboard$/)
    expect(state.applications).toHaveLength(1)
    expect(state.applications[0].notes).toBe('Keep these unsaved notes')
    await page.reload()
    await nav(page, 'List')
    await openDetails(page)
    await expect(page.locator('.notes-block p')).toHaveText('Keep these unsaved notes')
    await closeDetails(page)
  })
}

test('pending save prevents repeated submit events and sends exactly one request', async ({ page, context }) => {
  const state = await setup(page, context)
  await newForm(page)
  await submit(page).click()
  const save = await operation(state)
  await page.locator('form.application-form').evaluate((form) => {
    form.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }))
    form.dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }))
  })
  await expect(submit(page)).toBeDisabled()
  await expect(page.locator('form')).toHaveAttribute('aria-busy', 'true')
  await save.respond()
  await expect(page).toHaveURL(/dashboard$/)
  expect(state.saves).toHaveLength(1)
  expect(state.applications).toHaveLength(1)
})

for (const edit of [false, true]) {
  for (const failure of [false, true]) {
    test(`saving locks post-submit Notes edits without locking navigation (${edit ? 'edit' : 'create'}, ${failure ? 'failure/retry' : 'success'})`, async ({ page, context }) => {
      const state = await setup(page, context, edit ? [application(1, { notes: 'A' })] : [])
      if (edit) await nav(page, 'Edit')
      else await newForm(page)
      const notes = page.getByRole('textbox', { name: 'Notes', exact: true })
      await notes.fill('A')
      await notes.fill('B')
      // Submit without moving focus away from Notes, then attempt C before responding.
      await page.locator('form.application-form').evaluate((form) => form.requestSubmit())
      const save = await operation(state)
      expect(save.body.notes).toBe('B')
      await page.keyboard.press('ControlOrMeta+A')
      await page.keyboard.insertText('C')
      await expect(notes).toHaveValue('B')
      for (const field of await page.locator('fieldset input, fieldset select, fieldset textarea').all()) {
        await expect(field).toBeDisabled()
      }
      await expect(page.getByRole('button', { name: 'Back to dashboard', exact: true })).toBeEnabled()
      await expect(page.getByRole('button', { name: 'Progress', exact: true }).filter({ visible: true })).toBeEnabled()
      if (failure) {
        await save.fail()
        await expect(page.getByRole('alert')).toHaveText('Synthetic save failure')
        for (const field of await page.locator('fieldset input, fieldset select, fieldset textarea').all()) {
          await expect(field).toBeEnabled()
        }
        await expect(notes).toHaveValue('B')
        await notes.fill('C')
        await submit(page).click()
        const retry = await operation(state, 1)
        expect(retry.body.notes).toBe('C')
        await retry.respond()
      } else await save.respond()
      await expect(page).toHaveURL(/dashboard$/)
      expect(state.applications).toHaveLength(1)
      expect(state.applications[0].notes).toBe(failure ? 'C' : 'B')
      await page.reload()
      await nav(page, 'List')
      await openDetails(page)
      await expect(page.locator('.notes-block p')).toHaveText(failure ? 'C' : 'B')
      await closeDetails(page)
    })
  }
}

for (const failure of [false, true]) {
  test(`late ${failure ? 'failure' : 'success'} cannot affect another form at the same route`, async ({ page, context }) => {
    const state = await setup(page, context)
    await newForm(page)
    await submit(page).click()
    const save = await operation(state)
    await nav(page, 'Progress')
    await expect(page).toHaveURL(/progress$/)
    await nav(page, 'Dashboard')
    await newForm(page)
    await page.getByLabel('Company', { exact: false }).fill('Second form')
    if (failure) await save.fail()
    else await save.respond()
    // A fresh form can submit independently; wait for it to establish ordering.
    await submit(page).click()
    const second = await operation(state, 1)
    await expect(page).toHaveURL(/new$/)
    await expect(page.getByRole('alert')).toHaveCount(0)
    await expect(page.getByLabel('Company', { exact: false })).toHaveValue('Second form')
    await second.respond()
    await expect(page).toHaveURL(/dashboard$/)
    expect(state.applications).toHaveLength(failure ? 1 : 2)
  })
}

