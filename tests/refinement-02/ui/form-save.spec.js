test('session change during the edit version read stops the old session PATCH', async ({ page, context }) => {
  const state = await setup(page, context, [application(1)])
  await expect(status(page)).toBeVisible()
  await nav(page, 'Edit')
  await page.getByRole('textbox', { name: 'Notes', exact: true }).fill('Old session note')
  state.holdReads = true
  await submit(page).click()
  await expect.poll(() => state.reads.length).toBe(1)
  await nav(page, 'Sign out')
  state.holdReads = false
  state.user = { ...state.user, id: '00000000-0000-4000-8000-000000000002' }
  await signIn(page)
  await state.reads[0]()
  // Wait for another acknowledged save rather than relying on a sleep.
  await newForm(page)
  await submit(page).click()
  await (await operation(state)).respond()
  await expect(page).toHaveURL(/dashboard$/)
  expect(state.requests.filter((r) => r.method === 'PATCH' && r.table === 'applications')).toEqual([])
  expect(state.applications[0].notes).toBe('')
})

