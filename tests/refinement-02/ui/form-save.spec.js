import { expect, test } from '@playwright/test'
import { application, backend, nav, noOverflow, signIn, openDetails, closeDetails } from './fixtures.js'

const submit = (page) => page.locator('button[type="submit"]')
const status = (page) => page.getByRole('combobox', { name: 'Status for Synthetic 1', exact: true }).filter({ visible: true })
async function operation(state, index = 0, key = 'saves') {
  await expect.poll(() => state[key].length).toBe(index + 1)
  return state[key][index]
}
async function newForm(page) {
  await nav(page, 'Add application')
  await expect(page.getByRole('heading', { name: 'Add a new application' })).toBeVisible()
  await page.getByRole('textbox', { name: /^Company/ }).fill('  New company  ')
  await page.getByRole('textbox', { name: /^Role/ }).fill('  Engineer  ')
}
async function setup(page, context, rows = []) {
  const state = await backend(context, rows)
  state.controlSaves = true
  await signIn(page)
  return state
}

